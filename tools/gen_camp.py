#!/usr/bin/env python3
"""Writes Data/Camp.lua: Forever's camp items, the crafted objects you place at a camp (tent, chair, campfire kits,
anvil, loom and so on). Each is used up when placed.

A camp item is an item a profession recipe makes whose use effect is in one of the camp cooldown categories: 97 for the
camp objects (one hour, shared) and 2511 for the campfire kits (five minutes, shared). Category 97 also holds a few
spells no recipe makes (the Classic campfire, banners), which the recipe check leaves out, as it does the sleeping bag
and toys, which are not crafted.

Uses the same wago.tools cache as tools/gen_recipes.py. Run it by hand when Forever patches.

Usage: tools/gen_camp.py [--build 1.60.1.70707] [--refresh]
    no --build   use the newest wowf build wago.tools lists
    --refresh    download the tables again even if cached
"""
import argparse
from pathlib import Path

import wago
from gen_recipes import PROFESSIONS, CREATE_ITEM
from wago import cached_table, latest_build, rows

TABLES = ("SkillLineAbility", "SpellEffect", "ItemSparse", "ItemEffect", "ItemXItemEffect")
TARGET = Path(__file__).resolve().parent.parent / "Data" / "Camp.lua"

CAMP_CATEGORIES = {"97", "2511"}
# ItemSparse.AllowableRace_0 bits: Human (race 1) is bit 0, Orc (race 2) bit 1. A mask with only one of them is a
# one-faction item, such as the two Faction Banners.
HUMAN, ORC = 1, 2

wago.AGENT = "ProfessionsForever-camp-generator (run by hand)"


def generate(tables, build):
    recipe_line = {}
    for r in rows(tables["SkillLineAbility"]):
        line, spell = int(r["SkillLine"]), int(r["Spell"])
        if line in PROFESSIONS and r["AcquireMethod"] != "3" and spell not in recipe_line:
            recipe_line[spell] = line

    made_by = {}  # item -> recipe spell; the lowest spell ID when several make it
    for r in rows(tables["SpellEffect"]):
        spell = int(r["SpellID"])
        item = int(r["EffectItemType"] or 0)
        if spell in recipe_line and r["Effect"] == CREATE_ITEM and item > 0:
            made_by[item] = min(made_by.get(item, spell), spell)

    effects = {r["ID"]: r for r in rows(tables["ItemEffect"])}
    camp = {}  # item -> (recipe spell, skill line, category, cooldown seconds)
    for r in rows(tables["ItemXItemEffect"]):
        item, effect = int(r["ItemID"]), effects.get(r["ItemEffectID"])
        if item in made_by and effect and effect["SpellCategoryID"] in CAMP_CATEGORIES:
            spell = made_by[item]
            camp[item] = (spell, recipe_line[spell], int(effect["SpellCategoryID"]),
                          int(effect["CategoryCoolDownMSec"] or 0) // 1000)

    names, factions = {}, {}
    for r in rows(tables["ItemSparse"]):
        item = int(r["ID"])
        if item in camp:
            names[item] = r["Display_lang"]
            mask = int(r["AllowableRace_0"] or -1)
            if bool(mask & HUMAN) != bool(mask & ORC):
                factions[item] = "Alliance" if mask & HUMAN else "Horde"

    lines = [
        f"-- Generated by tools/gen_camp.py from wago.tools DB2 tables (product wowf, build {build}). Do not edit.",
        "local _, FP = ...",
        "",
        "-- [item ID] = { recipe spell ID, skill line ID, shared cooldown category, cooldown in seconds, faction or nil }",
        "FP.CampItems = {",
    ]
    for item in sorted(camp):
        spell, line, category, seconds = camp[item]
        faction = f', "{factions[item]}"' if item in factions else ""
        lines.append(f"    [{item}] = {{ {spell}, {line}, {category}, {seconds}{faction} }}, -- {names.get(item, '')}")
    lines.append("}")
    return "\n".join(lines) + "\n", len(camp)


def main():
    parser = argparse.ArgumentParser(description="Generate Data/Camp.lua from wago.tools data.")
    parser.add_argument("--build", help="Forever build, such as 1.60.1.70707 (default: the newest)")
    parser.add_argument("--refresh", action="store_true", help="download the tables again")
    args = parser.parse_args()

    build = args.build or latest_build()
    tables = {t: cached_table(build, t, args.refresh) for t in TABLES}
    text, count = generate(tables, build)
    old = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
    TARGET.write_text(text, encoding="utf-8")
    print(f"build {build}: {count} camp items -> {TARGET}" + (" (unchanged)" if text == old else " (changed)"))


if __name__ == "__main__":
    main()
