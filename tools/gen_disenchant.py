#!/usr/bin/env python3
"""Writes Data/Disenchant.lua: what disenchanting weapons and armor gives, with the odds.

The loot tables, and which items cannot be disenchanted, come from cmangos/classic-db (GPL-3.0), pinned to the
commit gen_npcs.py uses and cached the same way. The level brackets (item class, quality and item level range) come
from the wago.tools ItemDisenchantLoot table for the WoW: Forever build, which is how the game picks a table; the
classic-db table each bracket uses is the one its items use. Items present in Forever are checked one by one against
their bracket, and only the exceptions are listed. Run it by hand when the pin or the Forever build moves; leave the
attribution in the generated file.

Usage: tools/gen_disenchant.py [--build 1.60.1.70888] [--refresh]
    no --build   use the newest wowf build wago.tools lists
    --refresh    download the data again even if cached
"""
import argparse
from collections import Counter
from pathlib import Path

from gen_npcs import CLASSIC_DB, COMMIT, download_dump, load_dump, records
import wago
from wago import cached_table, latest_build, rows

wago.AGENT = "ProfessionsForever-disenchant-generator (run by hand)"

TARGET = Path(__file__).resolve().parent.parent / "Data" / "Disenchant.lua"
WAGO_TABLES = ("ItemDisenchantLoot", "ItemSparse")
CLASSES = (2, 4)      # weapon, armor
QUALITIES = (2, 3, 4)  # uncommon, rare, epic


def loot_tables(sql):
    """{ table id: [(item, percent, min, max)] }: the odds of each result, with a group's unlisted share split evenly."""
    entries = {}
    for r in records(sql["disenchant_loot_template"]):
        entries.setdefault(r["entry"], {}).setdefault(r["groupid"], []).append(r)
    tables = {}
    for entry, groups in entries.items():
        results = []
        for group, members in groups.items():
            listed = sum(r["ChanceOrQuestChance"] for r in members if r["ChanceOrQuestChance"] > 0)
            unlisted = [r for r in members if r["ChanceOrQuestChance"] == 0]
            share = max(0.0, 100.0 - listed) / len(unlisted) if group and unlisted else 0.0
            for r in members:
                chance = r["ChanceOrQuestChance"] or share
                if r["mincountOrRef"] < 0:
                    raise SystemExit(f"disenchant table {entry} refers to another table; the generator doesn't follow those")
                if chance > 0:
                    results.append((r["item"], chance, r["mincountOrRef"], r["maxcount"]))
        tables[entry] = sorted(results, key=lambda e: (-e[1], e[0]))
    return tables


def brackets(wago, items):
    """{ (class, quality): [(min item level, max item level, table id)] } for the Wago brackets."""
    used = {}
    for r in wago:
        key = (int(r["Class"]), int(r["Quality"]))
        low, high = int(r["MinLevel"]), int(r["MaxLevel"])
        tables = Counter(i["DisenchantID"] for i in items
                         if i["class"] == key[0] and i["Quality"] == key[1] and low <= i["ItemLevel"] <= high and i["DisenchantID"])
        used.setdefault(key, []).append([low, high, tables.most_common(1)[0][0] if tables else None])
    for key, found in used.items():
        found.sort()
        # A bracket no classic item falls in takes the table of its nearest higher one, or else its lower one.
        for i in reversed(range(len(found))):
            if found[i][2] is None:
                found[i][2] = next((f[2] for f in found[i + 1:] if f[2]), None) or next((f[2] for f in reversed(found[:i]) if f[2]), None)
    return used


def lookup(found, key, level):
    for low, high, table in found.get(key, ()):
        if low <= level <= high:
            return table


def generate(sql, wago, forever_ids):
    tables = loot_tables(sql)
    items = [i for i in records(sql["item_template"]) if i["class"] in CLASSES and i["Quality"] in QUALITIES]
    found = brackets(wago, items)
    never, override = [], {}
    for i in items:
        if i["entry"] not in forever_ids:
            continue
        if not i["DisenchantID"]:
            never.append(i["entry"])
        elif i["DisenchantID"] in tables and lookup(found, (i["class"], i["Quality"]), i["ItemLevel"]) != i["DisenchantID"]:
            override[i["entry"]] = i["DisenchantID"]
    used = {t for f in found.values() for _, _, t in f} | set(override.values())
    return {t: tables[t] for t in sorted(used) if t in tables}, found, sorted(never), override


def number(value):
    return f"{value:.1f}".rstrip("0").rstrip(".")


def render(tables, found, never, override, build):
    lines = [
        "-- Generated by tools/gen_disenchant.py - do not edit.",
        f"-- Loot tables and the items that cannot be disenchanted: {CLASSIC_DB} (GPL-3.0), commit {COMMIT}.",
        f"-- Level brackets: wago.tools ItemDisenchantLoot (product wowf, build {build}).",
        "local _, FP = ...",
        "",
        '-- [table id] = "item,percent,min,max;..." the chance of each result (one result per roll of a group)',
        "FP.DisenchantTables = {",
    ]
    for table, results in tables.items():
        lines.append(f'    [{table}] = "{";".join(f"{i},{number(c)},{lo},{hi}" for i, c, lo, hi in results)}",')
    lines += [
        "}",
        "",
        "-- [item class][quality] = { { min item level, max item level, table id }, ... }",
        "FP.DisenchantBrackets = {",
    ]
    for cls in CLASSES:
        lines.append(f"    [{cls}] = {{")
        for quality in QUALITIES:
            row = ", ".join(f"{{ {lo}, {hi}, {t} }}" for lo, hi, t in found.get((cls, quality), ()) if t)
            lines.append(f"        [{quality}] = {{ {row} }},")
        lines.append("    },")
    lines += [
        "}",
        "",
        "-- [item id] = table id, for items that don't use their bracket's table",
        "FP.DisenchantOverride = {",
    ]
    for item in sorted(override):
        lines.append(f"    [{item}] = {override[item]},")
    lines += [
        "}",
        "",
        "-- Weapons and armor of uncommon or better quality that cannot be disenchanted",
        'FP.DisenchantNever = "' + "," + ",".join(map(str, never)) + ',"',
    ]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description="Generate Data/Disenchant.lua from classic-db and wago.tools data.")
    parser.add_argument("--build", help="Forever build, such as 1.60.1.70888 (default: the newest)")
    parser.add_argument("--refresh", action="store_true", help="download the data again")
    args = parser.parse_args()

    build = args.build or latest_build()
    wago = list(rows(cached_table(build, "ItemDisenchantLoot", args.refresh)))
    forever_ids = {int(r["ID"]) for r in rows(cached_table(build, "ItemSparse", args.refresh))}
    download_dump(args.refresh)
    tables, found, never, override = generate(load_dump(), wago, forever_ids)
    text = render(tables, found, never, override, build)
    old = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
    TARGET.write_text(text, encoding="utf-8")
    print(f"build {build}: {len(tables)} tables, {len(never)} items that can't be disenchanted, {len(override)} overrides, "
          f"{len(text) // 1024} KB -> {TARGET}" + (" (unchanged)" if text == old else " (changed)"))


if __name__ == "__main__":
    main()
