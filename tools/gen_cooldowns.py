#!/usr/bin/env python3
"""Writes Data/Cooldowns.lua: the profession recipes that have a cooldown, and how long it is.

Downloads the DB2 tables it needs from wago.tools for the WoW: Forever build (product wowf), keeps them in a cache
folder (~/.cache/professionsforever/wago/<build>), and generates the file from them. Run it by hand when Forever
patches; it makes four requests at most, and none once a build is cached. wago.tools publishes no data terms, so
leave the attribution in the generated file.

Usage: tools/gen_cooldowns.py [--build 1.60.1.70707] [--refresh]
    no --build   use the newest wowf build wago.tools lists
    --refresh    download the tables again even if cached
"""
import argparse
import csv
import json
import sys
import urllib.request
from pathlib import Path

TABLES = ("SkillLineAbility", "SpellCooldowns", "SpellCategories", "SpellName")
CACHE = Path.home() / ".cache" / "professionsforever" / "wago"
TARGET = Path(__file__).resolve().parent.parent / "Data" / "Cooldowns.lua"
AGENT = {"User-Agent": "ProfessionsForever-cooldown-generator (run by hand)"}

# Skill lines of the professions this addon lists (Core/Professions.lua).
PROFESSIONS = {171, 164, 333, 202, 182, 773, 755, 165, 186, 393, 197, 129, 185, 356}
# Shorter cooldowns (campfires, Find Fish) are not worth tracking.
MIN_SECONDS = 600


def fetch(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers=AGENT), timeout=60) as response:
        return response.read()


def latest_build():
    builds = json.loads(fetch("https://wago.tools/api/builds"))["wowf"]
    return builds[0]["version"]


def cached_table(build, table, refresh):
    path = CACHE / build / f"{table}.csv"
    if refresh or not path.exists():
        print(f"downloading {table} ({build})")
        data = fetch(f"https://wago.tools/db2/{table}/csv?build={build}")
        if not data.startswith(b"ID,") and b",ID," not in data.split(b"\n", 1)[0]:
            sys.exit(f"{table}: the download doesn't look like a CSV table")
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    return path


def rows(path):
    with open(path, newline="", encoding="utf-8") as f:
        yield from csv.DictReader(f)


def generate(tables, build):
    names = {int(r["ID"]): r["Name_lang"] for r in rows(tables["SpellName"])}
    categories = {}
    for r in rows(tables["SpellCategories"]):
        categories[int(r["SpellID"])] = int(r["Category"] or 0)
    cooldowns = {}
    for r in rows(tables["SpellCooldowns"]):
        own, shared = int(r["RecoveryTime"] or 0), int(r["CategoryRecoveryTime"] or 0)
        spell = int(r["SpellID"])
        old = cooldowns.get(spell, (0, 0))
        cooldowns[spell] = (max(old[0], own), max(old[1], shared))

    out = {}
    for r in rows(tables["SkillLineAbility"]):
        line, spell = int(r["SkillLine"]), int(r["Spell"])
        # AcquireMethod 3 is the use effect of crafted devices (dragonlings, Battle Chicken), not a recipe.
        if line not in PROFESSIONS or r["AcquireMethod"] == "3" or spell not in cooldowns or spell in out:
            continue
        own, shared = cooldowns[spell]
        seconds = max(own, shared) // 1000
        if seconds < MIN_SECONDS:
            continue
        # Spells sharing a category all go on cooldown together when one is used.
        category = categories.get(spell) if shared > own and categories.get(spell) else None
        out[spell] = (seconds, line, category)

    lines = [
        f"-- Generated by tools/gen_cooldowns.py from wago.tools DB2 tables (product wowf, build {build}). Do not edit.",
        "local _, FP = ...",
        "",
        "-- [recipe spell ID] = { cooldown in seconds, skill line ID, shared cooldown category or nil }",
        "FP.CooldownData = {",
    ]
    for spell in sorted(out):
        seconds, line, category = out[spell]
        extra = f", {category}" if category else ""
        lines.append(f"    [{spell}] = {{ {seconds}, {line}{extra} }}, -- {names.get(spell, '?')}")
    lines.append("}")
    return "\n".join(lines) + "\n", len(out)


def main():
    parser = argparse.ArgumentParser(description="Generate Data/Cooldowns.lua from wago.tools data.")
    parser.add_argument("--build", help="Forever build, such as 1.60.1.70707 (default: the newest)")
    parser.add_argument("--refresh", action="store_true", help="download the tables again")
    args = parser.parse_args()

    build = args.build or latest_build()
    tables = {t: cached_table(build, t, args.refresh) for t in TABLES}
    text, count = generate(tables, build)
    old = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
    TARGET.parent.mkdir(exist_ok=True)
    TARGET.write_text(text, encoding="utf-8")
    print(f"build {build}: {count} recipes -> {TARGET}" + (" (unchanged)" if text == old else " (changed)"))


if __name__ == "__main__":
    main()
